/* Public Tizen application APIs. No Mac server, network address or credentials. */
(function () {
  'use strict';
  var IDS = {
    stremio: 'IkWsFHtOY9.Stremio', netflix: 'org.tizen.netflix-app',
    disneyplus: 'MCmYXNxgcu.DisneyPlus', youtube: '9Ur5IzDKqV.TizenYouTube',
    appletv: 'com.samsung.tv.aria-video', primevideo: 'org.tizen.primevideo',
    abciview: 'mWK87Xghap.ABCiview', sbs: 'OyE7OuxlUi.SBSOnDemand',
    hbomax: '5b8c3eb16b.BeamCTVDev', paramount: 'rJyOSqC6Up.CBSAllAccess', peacock: 'gzcc4LRFBF.Peacock',
    applemusic: 'org.tizen.apple.apple-music'
  };
  var STREAMING = ['as6cYRgkPy.Binge', '73iTZRTc34.Stan', '5b8c3eb16b.BeamCTVDev',
    'KaLitts8bq.tenplaySamsungTizen', 'eYuOiOLYQX.KayoSports', 'Ne2ZsPWdKl.9NOW',
    '3KA0pm7a7V.TubiTV', 'rJeHak5zRg.Spotify', 'icp4AvUPiA.7plus'];
  var CONSUMER_SYSTEM = ['org.tizen.browser', 'com.microsoft.copilot'];
  var EXTRA_BRANDS = {'rJeHak5zRg.Spotify': 'spotify', '5b8c3eb16b.BeamCTVDev': 'hbomax', '3KA0pm7a7V.TubiTV': 'tubi'};
  var INTERNAL = ['adplatform.ADPlayer', 'WykOS4t4F0.cmsWebApp', '25emanual3.emanual',
    'ZODRT12q2l.WebAccountExtension', 'ByJlgt0XeD.CastSettingsApp', 'tv6pbVMQFF.PrivacyChoices'];
  var SELF = 'WxBxsP0SwL.FrameHome';
  var inputVisible = false, inputRequest = 0, cancelInput = null;
  function api() { return window.tizen && window.tizen.application; }
  function unavailable(done) {
    done({ message: 'Open CleanFrame on the TV to use this control.', detail: 'The web preview cannot control the TV.' });
  }
  function failure(err) {
    return { message: 'The TV could not open this screen.', detail: err && (err.message || err.name) || 'Try again, or press Back to return.' };
  }
  function bounded(done) {
    var finished = false, timer = setTimeout(function () { finish({ message: 'The TV did not respond. Please try again.' }); }, 8000);
    function finish(err, value) { if (finished) return; finished = true; clearTimeout(timer); done(err, value); }
    return finish;
  }
  function launchApp(id, done) {
    if (!api()) { unavailable(done); return; }
    var finish = bounded(done);
    try { api().launch(id, function () { finish(null); }, function (err) { finish(failure(err)); }); }
    catch (err) { finish(failure(err)); }
  }
  function launch(brand, done) {
    if (!IDS[brand]) { done({message: 'This app has no launch target.'}); return; }
    launchApp(IDS[brand], done);
  }
  function input(number, done) {
    if (!window.tizen || !tizen.tvwindow || !tizen.systeminfo) { unavailable(done); return; }
    var request = ++inputRequest, finish = bounded(done);
    inputVisible = true;
    cancelInput = function () { finish(null); };
    function fail(err) { if (request !== inputRequest) return; inputVisible = false; finish(err); }
    try {
      tizen.systeminfo.getPropertyValue('VIDEOSOURCE', function (info) {
        if (request !== inputRequest) return;
        var source = null;
        info.connected.forEach(function (item) {
          if (item.type === 'HDMI' && item.number === number) source = item;
        });
        if (!source) {
          fail({ message: 'HDMI ' + number + ' is not connected.', detail: 'Check the device is powered on and its HDMI cable is connected.' });
          return;
        }
        try {
          tizen.tvwindow.setSource(source, function () {
            if (request !== inputRequest) return;
            try {
              tizen.tvwindow.show(function () {
                if (request !== inputRequest) {
                  if (!inputVisible) tizen.tvwindow.hide(function () {}, function () {}, 'MAIN');
                  return;
                }
                finish(null);
              }, function (err) { fail(failure(err)); }, ['0', '0', '100%', '100%'], 'MAIN', 'FRONT');
            } catch (err) { fail(failure(err)); }
          }, function (err) { fail(failure(err)); });
        } catch (err) { fail(failure(err)); }
      }, function (err) { fail(failure(err)); });
    } catch (err) { fail(failure(err)); }
  }
  function closeInput(done) {
    inputRequest++;
    if (cancelInput) { cancelInput(); cancelInput = null; }
    var finish = bounded(done);
    try {
      tizen.tvwindow.hide(function () { inputVisible = false; finish(null); }, function (err) { finish(failure(err)); }, 'MAIN');
    } catch (err) { finish(failure(err)); }
  }
  function art(done) {
    if (!api()) { unavailable(done); return; }
    var finish = bounded(done);
    try {
      var data = [new tizen.ApplicationControlData('mode', ['fullscreen']), new tizen.ApplicationControlData('requester', ['mobile'])];
      var control = new tizen.ApplicationControl('http://tizen.org/appcontrol/operation/default', null, null, null, data);
      api().launchAppControl(control, 'org.tizen.art-app', function () { finish(null); }, function (err) { finish(failure(err)); });
    } catch (err) { finish(failure(err)); }
  }
  function home(done) { launchApp('com.samsung.tv.csfs', done); }
  function settings(done) { launchApp('com.samsung.tv.coba.setting', done); }
  function apps(done) {
    if (!api()) { unavailable(done); return; }
    var finish = bounded(done);
    try {
      api().getAppsInfo(function (list) {
        var known = {}, seen = {}, result = [];
        Object.keys(IDS).forEach(function (brand) { known[IDS[brand]] = brand; });
        list.forEach(function (a) {
          var primary = !!known[a.id], stream = STREAMING.indexOf(a.id) >= 0;
          var consumer = /^[A-Za-z0-9]{10}\.[A-Za-z0-9_-]+$/.test(a.id) || CONSUMER_SYSTEM.indexOf(a.id) >= 0;
          if (a.id === SELF || INTERNAL.indexOf(a.id) >= 0 || seen[a.id] || !a.name || (!primary && !stream && (!a.show || !consumer))) return;
          if (!primary && /(?:service|worker|preview|promotion|plugin|launcher|test|sdk|^ep[ -]|factory|daemon)/i.test(a.name + ' ' + a.id)) return;
          if (/-dummy$/.test(a.id) || a.id === 'com.samsung.tv.cobalt-yt') return;
          seen[a.id] = true;
          result.push({ appId: a.id, name: a.name, brand: known[a.id] || EXTRA_BRANDS[a.id] || '', icon: a.iconPath || '', rank: primary ? Object.keys(IDS).indexOf(known[a.id]) : (stream ? 20 : 30) });
        });
        result.sort(function (a, b) { return a.rank - b.rank || a.name.toLowerCase().localeCompare(b.name.toLowerCase()); });
        finish(null, result);
      }, function (err) { finish(failure(err)); });
    } catch (err) { finish(failure(err)); }
  }
  window.FrameDevice = { launch: launch, launchApp: launchApp, input: input, closeInput: closeInput, inputVisible: function () { return inputVisible; }, art: art, home: home, settings: settings, apps: apps };
}());
